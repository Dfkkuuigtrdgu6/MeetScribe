-- Add description column to templates
ALTER TABLE templates ADD COLUMN IF NOT EXISTS description text;

-- Update templates with clearer, more distinct prompts and add descriptions
UPDATE templates SET
  description = '适合正式会议场景，自动提取摘要、关键要点、待办事项和决议',
  prompt = '你是一个专业的会议纪要助手。请根据以下转写内容生成结构化会议纪要，必须包含以下部分：

【会议摘要】用2-3句话概括会议的核心议题和主要结论。

【关键要点】列出会议讨论的核心要点，每条一句话，编号排列。

【待办事项】列出需要跟进的任务，每条包含：任务描述、负责人（如转写中未提及则标注"待定"）、截止日期（如未提及则标注"待定"）。

【决议结论】列出会议中达成的明确决定和结论。'
WHERE name = '会议纪要';

